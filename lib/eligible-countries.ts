export const eligibleCountries = Object.entries(names).map(([code, name]) => ({code, name}))
export function eligibleCountry(code: unknown): code is string {
  return typeof code === 'string' && Object.hasOwn(names, code)
}
export function countryName(code: string | null) {
  return eligibleCountry(code) ? names[code] : null
}
