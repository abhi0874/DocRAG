import {afterEach,beforeEach,expect,it,vi} from 'vitest'
const mocks=vi.hoisted(()=>({embed:vi.fn(),limit:vi.fn()}))
vi.mock('ai',()=>({embed:mocks.embed,embedMany:vi.fn()}))
vi.mock('@/lib/security/limits',()=>({consumeLimit:mocks.limit}))
vi.mock('@/lib/retrieval',()=>({retrieve:vi.fn()}))
vi.mock('@/lib/demo-provider',()=>({demoGoogle:()=>Object.assign(()=>({}),{embedding:()=>({})})}))
beforeEach(()=>{
  vi.resetModules();vi.clearAllMocks()
  vi.stubEnv('DOCRAG_DEPLOYMENT','recruiter-demo');vi.stubEnv('AI_PROVIDER','gemini');vi.stubEnv('DOCRAG_WORKSPACE_ENABLED','true');vi.stubEnv('RERANKER_ENABLED','false');vi.stubEnv('RESPONSE_CACHE_ENABLED','false')
  mocks.limit.mockResolvedValue(undefined)
  mocks.embed.mockResolvedValue({embedding:Array(1536).fill(1)})
})
afterEach(()=>vi.unstubAllEnvs())
it('checks shared byte/request quotas before each individually bounded cloud call',async()=>{
  const {embedChunks}=await import('@/lib/rag')
  const vectors=await embedChunks(['Public alpha.','Public beta.'])
  expect(vectors).toHaveLength(2);expect(Math.hypot(...vectors[0])).toBeCloseTo(1)
  expect(mocks.embed).toHaveBeenCalledTimes(2)
  expect(mocks.limit.mock.invocationCallOrder[2]).toBeLessThan(mocks.embed.mock.invocationCallOrder[0])
  expect(mocks.limit.mock.invocationCallOrder[5]).toBeLessThan(mocks.embed.mock.invocationCallOrder[1])
  for(const [call] of mocks.embed.mock.calls)expect(call).toMatchObject({maxRetries:0,abortSignal:expect.any(AbortSignal),providerOptions:{google:{outputDimensionality:1536,taskType:'RETRIEVAL_DOCUMENT'}}})
})
it('rejects exhausted quotas before transmitting text',async()=>{
  mocks.limit.mockRejectedValue(new Error('quota exhausted'))
  const {embedChunks}=await import('@/lib/rag')
  await expect(embedChunks(['Public alpha.'])).rejects.toThrow('quota')
  expect(mocks.embed).not.toHaveBeenCalled()
})
it('does not start another chunk after cancellation',async()=>{
  const abort=new AbortController()
  mocks.embed.mockImplementationOnce(async()=>{abort.abort();return {embedding:Array(1536).fill(1)}})
  const {embedChunks}=await import('@/lib/rag')
  await expect(embedChunks(['Public alpha.','Public beta.'],abort.signal)).rejects.toThrow()
  expect(mocks.embed).toHaveBeenCalledTimes(1)
})
it('does not substitute malformed vectors or retry provider errors',async()=>{
  const {embedChunks}=await import('@/lib/rag')
  mocks.embed.mockResolvedValueOnce({embedding:Array(768).fill(1)})
  await expect(embedChunks(['Public alpha.'])).rejects.toThrow('space mismatch')
  mocks.embed.mockRejectedValueOnce(new Error('provider unavailable'))
  await expect(embedChunks(['Public beta.'])).rejects.toThrow('provider unavailable')
  expect(mocks.embed).toHaveBeenCalledTimes(2)
})
it('keeps indexing disabled when the workspace rollout is off',async()=>{
  vi.stubEnv('DOCRAG_WORKSPACE_ENABLED','false')
  const {embedChunks}=await import('@/lib/rag')
  await expect(embedChunks(['Public alpha.'])).rejects.toThrow('bootstrap')
  expect(mocks.embed).not.toHaveBeenCalled()
})
